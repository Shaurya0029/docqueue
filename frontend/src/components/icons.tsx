export type IconName = keyof typeof ICONS;

export function Icon({ name, className = "h-5 w-5", strokeWidth = 2, ...props }: { name: IconName } & LucideProps) {
  const Component = ICONS[name];
  return <Component aria-hidden="true" className={className} strokeWidth={strokeWidth} {...props} />;
}
